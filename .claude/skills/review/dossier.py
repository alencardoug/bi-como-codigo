#!/usr/bin/env python3
"""Builds the review dossier of a delivery.

Two halves, and the split is deliberate:

* what the **machine** knows — commits, files, and the literal output of the
  verification commands — is collected here and passes through nobody's memory;
* what only the **author** knows — what was not verified, which premises about
  the environment they assumed, where they hesitated — is left marked as pending
  in the file, and `--verify` refuses the dossier while any mark remains.

The rule that holds it all up: **a claim of measurement needs pasted command
output**. What has no output is not a measurement — it is an assumption, and it
goes into the assumptions section by construction, not by the author's virtue.

Ported from `dossie.py` of the `revisao` skill of mvp_eng_dados_1 at `26b58b3`;
only the environment section is this project's.

Usage:
    uv run python .claude/skills/review/dossier.py --since <ref>   # builds
    uv run python .claude/skills/review/dossier.py --verify        # validates

`--output` diverts the dossier to another file. It exists for when `DOSSIER.md`
holds a review still open: overwriting it would erase findings nobody answered,
and `git` history does not replace a finding the author needs in front of them.
Two reviews in progress are two files.
"""

from __future__ import annotations

import argparse
import pathlib
import re
import subprocess
import sys

#: Terminal colour sequences. They make output unreadable inside a `.md`, and
#: the dossier exists to be read — also by whoever did not open it in a terminal.
ANSI = re.compile(r"\x1b\[[0-9;]*[A-Za-z]")

ROOT = pathlib.Path(__file__).resolve().parents[3]
COMMANDS = pathlib.Path(__file__).with_name("commands.txt")

#: Where the dossier lands when `--output` says nothing else. Not `REVIEW.md`:
#: that is the permanent record of the plan review.
DEFAULT = ROOT / "DOSSIER.md"

#: The mark the author must replace. The dossier does not close with it inside.
PENDING = "<<FILL IN>>"

#: How a generated file announces itself. A file carrying this in its first
#: lines is **derived**: reviewing it line by line is reviewing a program's
#: output instead of the program.
GENERATED_MARKS = ("generated by", "gerado por", "do not edit", "não edite")


def _git(*args: str) -> str:
    return subprocess.run(
        ["git", *args], cwd=ROOT, capture_output=True, text=True, check=True
    ).stdout.strip()


def _is_generated(path: str) -> bool:
    file = ROOT / path
    if not file.is_file():
        return False
    try:
        header = "".join(file.open(encoding="utf-8").readlines()[:6]).lower()
    except (UnicodeDecodeError, OSError):
        return False
    return any(mark in header for mark in GENERATED_MARKS)


def _commands() -> list[str]:
    if not COMMANDS.exists():
        COMMANDS.write_text(
            "# Verification commands of this project, one per line.\n"
            "# The dossier runs each and pastes its output. A line with # is ignored.\n"
            "# Examples: make test · make check · npm test\n",
            encoding="utf-8",
        )
        return []
    return [
        line.strip()
        for line in COMMANDS.read_text(encoding="utf-8").splitlines()
        if line.strip() and not line.strip().startswith("#")
    ]


def _run(command: str, seconds: int) -> tuple[int, str]:
    try:
        output = subprocess.run(
            command, shell=True, cwd=ROOT, capture_output=True, text=True, timeout=seconds
        )
    except subprocess.TimeoutExpired:
        return 124, f"(exceeded {seconds}s without finishing)"
    clean = ANSI.sub("", output.stdout + output.stderr).strip()
    lines = [line.rstrip() for line in clean.splitlines() if line.strip()]
    return output.returncode, "\n".join(lines[-12:]) or "(no output)"


def _filled_findings(target: pathlib.Path) -> int:
    """How many written findings exist in the dossier about to be overwritten.

    The question matters because the dossier is transient but the findings are
    **not**: they are what the reviewer produced and what the author still owes
    an answer to. Regenerating over them erases the other side's work.
    """
    if not target.exists():
        return 0
    body = target.read_text(encoding="utf-8").split("## Review findings", 1)
    if len(body) < 2:
        return 0
    findings = 0
    for line in body[1].splitlines():
        if not line.startswith("|"):
            continue
        first = line.split("|")[1].strip()
        # Header, separator and the legend row of the template are not findings.
        if first and first != "#" and not set(first) <= {"-", ":"}:
            findings += 1
    return findings


def build(
    since: str,
    seconds: int,
    until: str = "HEAD",
    target: pathlib.Path = DEFAULT,
    force: bool = False,
) -> pathlib.Path:
    # The top is **pinned** to the SHA, not left as `HEAD`. A dossier that says
    # `base..HEAD` describes another range as soon as a new commit lands — and
    # the reviewer reads the wrong diff without noticing, because the list of
    # commits in the dossier still looks right.
    findings = _filled_findings(target)
    if findings and not force:
        sys.exit(
            f"{target.relative_to(ROOT)} has {findings} finding(s) of a review still "
            "open — building over it would erase them.\n"
            "Use --output <another file> for the new review, close the current one first, "
            "or --force if you know these findings were answered."
        )

    until = _git("rev-parse", "--short", until)
    commits = _git("log", "--reverse", "--format=%h %s", f"{since}..{until}")
    if not commits:
        sys.exit(f"no commit in {since}..{until} — nothing to review")

    files = [
        line.split("\t", 1)[1]
        for line in _git("diff", "--name-status", f"{since}..{until}").splitlines()
        if "\t" in line
    ]
    generated = [f for f in files if _is_generated(f)]
    written = [f for f in files if f not in generated]

    runs = []
    for command in _commands():
        code, output = _run(command, seconds)
        runs.append((command, code, output))

    parts = [
        "# Review of the delivery",
        "",
        "> Dossier generated by `.claude/skills/review/dossier.py`. **Transient**: it leaves in the",
        "> commit that closes the review. It is not project documentation and does not enter the",
        "> map of the README.",
        ">",
        "> **It is an invitation, not an order.** It does not replace what the Owner asked in this",
        "> session: if the request was to implement, implement — this file stays here waiting for",
        "> whoever reviews.",
        "",
        "## 1. Scope",
        "",
        f"Range: `{since}..{until}` — read the diff, it is not repeated here.",
        "",
        "Both ends are fixed SHAs on purpose: a dossier that said `..HEAD` would describe another",
        "range at the next commit, with the list below unchanged.",
        "",
        "```",
        commits,
        "```",
        "",
        "## 2. Review map",
        "",
        "Where to spend effort. **An error in derived output is a symptom: fix it in the declaration.**",
        "",
        f"### Written by hand — {len(written)} files",
        "",
        *(f"- `{f}`" for f in written),
        "",
        f"### Generated — {len(generated)} files, review by sample",
        "",
        *(f"- `{f}`" for f in generated or ["(none)"]),
        "",
        f"**Declaration of this delivery:** {PENDING} — which of these files are the *declaration*",
        "the others come from, and therefore need a full review.",
        "",
        "## 3. What was measured",
        "",
        "Literal output, not a summary. A command with no output here is not a measurement.",
        "",
    ]

    for command, code, output in runs:
        mark = "✓" if code == 0 else f"✗ (exit {code})"
        parts += [f"### `{command}` {mark}", "", "```", output, "```", ""]
    if not runs:
        parts += [
            f"{PENDING} — no command declared in",
            "`.claude/skills/review/commands.txt`. Without one, **nothing** in this delivery is measured.",
            "",
        ]

    parts += [
        "## 4. What was NOT verified",
        "",
        "The most useful section of the dossier, and the one the author least wants to write.",
        "Every claim with no command output in section 3 belongs here.",
        "",
        f"{PENDING}",
        "",
        "## 5. Assumptions about the environment",
        "",
        "What was assumed about a tool, database or service and **not** confirmed in this",
        "delivery. It is the class of error that passes code review unseen.",
        "",
        f"{PENDING}",
        "",
        "## 6. Environment the review needs",
        "",
        "What must be up for the probes, and how to bring it up. **Bringing up is allowed;",
        "changing data is not.** \"Leave the environment as you found it\" applies to the content of",
        "databases and volumes — not to a stopped or absent container, which the reviewer starts.",
        "",
        "| Needs | How to bring it up | How to check |",
        "|---|---|---|",
        "| The locked Python environment of this repository | `make sync` | `uv run --frozen python -c 'import bi_como_codigo'` |",
        "| A checkout of mvp_eng_dados_1, for the pinned links and the probes | `ENG_DADOS_DIR=<checkout>` in the environment | `git -C \"$ENG_DADOS_DIR\" cat-file -t 26b58b3` prints `commit` |",
        "| The eng_dados databases, for the SQL probes of `evidence/` | `make up` in the eng_dados checkout — recreates the containers on the existing volumes; nothing is regenerated | `make ps` there; each probe runs through `evidence/20261022/ro.sh`, in a read-only session |",
        "",
        "**Never** in a review: any eng_dados target that rewrites data — `make reset`, `seed-*`,",
        "`CARGA=1`, `FATO=1`, or anything with `FORCE=1`. That is execution, not review. If the",
        "environment cannot be prepared, the unavailability goes into the findings and what depended",
        "on it stays **not measured** — never inferred.",
        "",
        f"{PENDING} — what **this** review needs to find up beyond the minimum above, and in what",
        "state.",
        "",
        "## 7. Where I hesitated",
        "",
        "Decisions that could have gone the other way, with the reason they went this one.",
        "",
        f"{PENDING}",
        "",
        "---",
        "",
        "## Review findings",
        "",
        "Filled in by the reviewer. One finding per line, with a verdict.",
        "",
        "| # | Where | Finding | Verdict | Status |",
        "|---|---|---|---|---|",
        "| | | | `blocking` · `adjustment` · `observation` | |",
        "",
    ]

    target.write_text("\n".join(parts) + "\n", encoding="utf-8")
    return target


def verify(target: pathlib.Path = DEFAULT) -> int:
    if not target.exists():
        print(f"no dossier at {target.relative_to(ROOT)}")
        return 1
    text = target.read_text(encoding="utf-8")
    pending = text.count(PENDING)
    failures = text.count("✗")
    if pending:
        print(f"{pending} section(s) still with {PENDING} — the dossier is not ready")
        return 1
    if failures:
        print(f"{failures} verification command(s) failed; explain each before handing off")
        return 1
    print("dossier complete: no pending mark and no failing check")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="Review dossier of a delivery.")
    parser.add_argument("--since", help="ref to compare from, e.g. origin/main")
    parser.add_argument("--until", default="HEAD", help="top of the range; HEAD by default")
    parser.add_argument("--timeout", type=int, default=1800, help="seconds per command")
    parser.add_argument("--verify", action="store_true", help="validates the existing dossier")
    parser.add_argument(
        "--output",
        help="dossier file; DOSSIER.md by default. Use another when it holds an open review",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="builds over unanswered findings; only after checking they were answered",
    )
    args = parser.parse_args()

    target = ROOT / args.output if args.output else DEFAULT

    if args.verify:
        return verify(target)
    if not args.since:
        parser.error("give --since <ref> or --verify")
    path = build(args.since, args.timeout, args.until, target, args.force)
    print(f"dossier at {path.relative_to(ROOT)} — fill in the sections marked {PENDING}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
